#!/usr/bin/env bash
# Wires this repo into Claude Code for installs that copy or symlink skill folders instead of
# installing the plugin: registers the skills' hooks, imports the global instructions,
# writes the subagent roles in agents/, and disables claude.ai-synced copies of these skills.
# Idempotent; rerun after pulling.
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
claude_dir=${CLAUDE_CONFIG_DIR:-$HOME/.claude}
settings=$claude_dir/settings.json
memory=$claude_dir/CLAUDE.md

command -v jq >/dev/null || { echo "install.sh needs jq" >&2; exit 1; }
mkdir -p "$claude_dir"
[ -s "$settings" ] || echo '{}' > "$settings"

# Synced claude.ai plugins load as `<name>@synced` next to the skill folders, so each skill
# would be listed twice. Disable every synced plugin that shares a name with a skill here.
skills=$(for d in "$repo"/*/; do [ -f "$d/SKILL.md" ] && basename "$d"; done | jq -R . | jq -s .)

jq --arg push "\"$repo/commit-rules/hooks/pre-push-reminder.sh\"" \
  --arg pr "\"$repo/visual-pr-description/hooks/pr-create-reminder.sh\"" \
  --argjson skills "$skills" '
  def ours: [.hooks[]?.command // empty] | any(test("pre-push-reminder\\.sh|pr-create-reminder\\.sh"));
  .hooks.PreToolUse = ([.hooks.PreToolUse[]? | select(ours | not)] + [
    {matcher: "Bash", hooks: [{type: "command", command: $push}]},
    {matcher: "Bash|mcp__.*__(create|update)_pull_request", hooks: [{type: "command", command: $pr}]}
  ])
  | .enabledPlugins = ((.enabledPlugins // {}) + ($skills | map({key: "\(.)@synced", value: false}) | from_entries))
  ' "$settings" > "$settings.tmp" && mv "$settings.tmp" "$settings"

# Import instead of copying, so edits to setup/CLAUDE.md apply without rerunning.
start='<!-- juraj-skills:start -->'
end='<!-- juraj-skills:end -->'
block="$start
@$repo/setup/CLAUDE.md
$end"
touch "$memory"
if grep -qF "$start" "$memory"; then
  BLOCK=$block awk -v s="$start" -v e="$end" '
    $0 == s { print ENVIRON["BLOCK"]; skip = 1; next }
    $0 == e { skip = 0; next }
    !skip' "$memory" > "$memory.tmp" && mv "$memory.tmp" "$memory"
else
  [ -s "$memory" ] && echo >> "$memory"
  echo "$block" >> "$memory"
fi

# Subagent roles: render agents/*.md into Claude Code and Codex formats.
# Generated files carry a marker so stale ones can be removed.
claude_model() { case $1 in strong) echo claude-opus-5-5 ;; mid) echo claude-sonnet-5-5 ;; cheap) echo claude-haiku-5-5 ;; esac; }
codex_model() { case $1 in strong) echo "gpt-6.1-sol high" ;; mid) echo "gpt-6.1-terra medium" ;; cheap) echo "gpt-6-luna low" ;; esac; }
marker="generated by setup/install.sh from agents/"
field() { awk -v k="$1" 'NR > 1 && /^---$/ { exit } NR > 1 && index($0, k ": ") == 1 { print substr($0, length(k) + 3) }' "$2"; }
body() { awk 'n >= 2 { print } /^---$/ { n++ }' "$1"; }

codex_dir=${CODEX_HOME:-$HOME/.codex}
targets=("$claude_dir/agents")
[ -d "$codex_dir" ] && targets+=("$codex_dir/agents")
for dir in "${targets[@]}"; do
  mkdir -p "$dir"
  { grep -lF "$marker" "$dir"/*.md "$dir"/*.toml 2>/dev/null || true; } | while read -r f; do rm "$f"; done
done

for src in "$repo"/agents/*.md; do
  name=$(field name "$src")
  [ -n "$name" ] || continue
  tier=$(field tier "$src")
  desc=$(field description "$src")
  model=$(claude_model "$tier")
  [ -n "$model" ] || { echo "$src: unknown tier '$tier'" >&2; exit 1; }
  {
    echo "---"
    echo "name: $name"
    echo "description: $desc"
    echo "model: $model"
    [ "$(field readonly "$src")" = true ] && echo "tools: Read, Grep, Glob, Bash, WebFetch, WebSearch"
    echo "---"
    echo "<!-- $marker$(basename "$src"). Edit that file, not this one. -->"
    echo
    body "$src"
  } > "$claude_dir/agents/$name.md"

  if [ -d "$codex_dir" ]; then
    read -r cmodel effort <<< "$(codex_model "$tier")"
    cname=$(field codex_name "$src")
    cname=${cname:-$name}
    {
      echo "# $marker$(basename "$src"). Edit that file, not this one."
      echo "name = $(jq -Rn --arg v "$cname" '$v')"
      echo "description = $(jq -Rn --arg v "$desc" '$v')"
      echo "model = \"$cmodel\""
      echo "model_reasoning_effort = \"$effort\""
      echo "developer_instructions = $(body "$src" | jq -Rs .)"
    } > "$codex_dir/agents/$cname.toml"
  fi
done

echo "Hooks, global instructions, subagents, and synced-duplicate suppression installed from $repo"
